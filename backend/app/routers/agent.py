@router.get("/status")
@_limiter.limit("60/minute")
def status_endpoint(
    request: Request,
    format: str = Query(default="text", description="'text' (default) or 'json'"),
    identity: dict = _READ,
):
    """Whether each account can post right now and why not, when the next post
    is due, how deep each queue is, and which machines are still reporting."""
    with conn() as c:
        data = agent_svc.status_report(c)
    return _respond(data, agent_svc.render_status(data), format)


@router.get("/queue")
@_limiter.limit("60/minute")
def queue_endpoint(
    request: Request,
    account: str | None = Query(default=None, description="restrict to one account"),
    reviewed: bool | None = Query(default=None, description="true to show only human-approved drafts"),
    limit: int = Query(default=20, ge=1, le=100, description="how many drafts to return"),
    format: str = Query(default="text", description="'text' (default) or 'json'"),
    identity: dict = _READ,
):
    """The drafts waiting to publish, what each is missing, and roughly when
    each one will go out."""
    with conn() as c:
        data = agent_svc.queue_report(
            c, account=account, reviewed=reviewed, limit=limit
        )
    return _respond(data, agent_svc.render_queue(data), format)


