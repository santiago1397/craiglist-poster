class PostNowBody(BaseModel):
    draft_id: int = Field(description="id of a queued, reviewed draft")


@router.post("/post-now", status_code=status.HTTP_202_ACCEPTED)
@_limiter.limit("10/minute")
def post_now_endpoint(
    request: Request,
    body: PostNowBody,
    identity: dict = Depends(require_agent_post),
):
    """Publish a draft a human has already reviewed. Requires a 'post'-scope key
    sent as a header."""
    with tx() as c:
        draft = drafts_svc.get_draft(c, body.draft_id)
        if draft is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"No draft with id {body.draft_id}.",
            )
        # The line an agent may not cross. Guardrails stop an account being
        # over-posted, but nothing else stops the wrong *words* going out under
        # this licence number and phone. A human reviewing the copy is the only
        # control there is, and it is not one this endpoint gets to skip.
        if not draft["reviewed"]:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=(
                    f"Draft {body.draft_id} has not been reviewed by a human. "
                    "Only reviewed drafts can be published through this API. "
                    "Ask the operator to review it in the dashboard first."
                ),
            )
        try:
            result = drafts_svc.request_post(
                c,
                body.draft_id,
                # Attribution, so a post that went out off-cadence can be
                # explained later. 'admin' would be a lie.
                requested_by=f"agent:{identity['label'] or identity['id']}",
            )
        except ValueError as e:
            raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(e))
        except drafts_svc.NotEligible as e:
            # Verbatim, and not retryable. These are the same strings the
            # dashboard and `cl status` print.
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail={
                    "message": f"{draft['account']} cannot post right now",
                    "reasons": e.reasons,
                    "advice": (
                        "This is a guardrail, not a transient error. Do not "
                        "retry — report these reasons to the user."
                    ),
                },
            )

    return {
        "requested": True,
        "draft_id": body.draft_id,
        "account": draft["account"],
        "title": draft["title"],
        "message": (
            "Request accepted. Nothing has published yet: the posting desktop "
            "picks this up on its next poll (~15 seconds) and then drives the "
            "Craigslist form. Check /agent/posts in a few minutes to confirm, "
            "and /agent/problems if it does not appear."
        ),
        "eligibility": jsonable_encoder(result.get("eligibility")),
    }
