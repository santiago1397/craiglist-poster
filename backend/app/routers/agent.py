"""The agent surface — one URL to learn the API, one URL per answer.

Designed against a specific constraint: **many AI fetch tools cannot set HTTP
headers.** Claude Code's WebFetch cannot. An API that requires
`Authorization: Bearer` therefore excludes every agent that lacks a shell,
which is most of them. So reads accept `?key=`, and the cost — the key landing
in access logs — is paid only on the verb where it is survivable. The one write
here is header-only (see `security.require_agent_post`).

Responses are plain text by default because the caller is a language model, and
`?format=json` when something needs to parse. Both render from the identical
dict, so they cannot describe different states.

`/agent/help` is generated by walking this router's own routes rather than
written by hand. A hand-written manual is wrong the first time someone adds a
parameter and forgets the docs — and a confidently wrong manual is worse for an
agent than no manual, because it will follow it.
"""
from __future__ import annotations

import inspect

import fastapi.params
from fastapi import APIRouter, Depends, HTTPException, Query, Request, status
from fastapi.encoders import jsonable_encoder
from fastapi.responses import JSONResponse, PlainTextResponse
from fastapi.routing import APIRoute
from pydantic import BaseModel, Field
from slowapi import Limiter
from slowapi.util import get_remote_address

from ..db import conn, tx
from ..security import require_agent_post, require_agent_read
from ..services import agent as agent_svc
from ..services import drafts as drafts_svc

router = APIRouter()

# Per-router limiter, matching the pattern in routers/auth.py. Generous enough
# that no honest caller will notice, tight enough that a retry loop cannot use
# the box as a treadmill — every report below fans out into several queries.
_limiter = Limiter(key_func=get_remote_address)

_READ = Depends(require_agent_read)


def _respond(data: dict, text: str, fmt: str):
    """Text unless JSON was asked for. Same dict behind both."""
    if fmt == "json":
        return JSONResponse(jsonable_encoder(data))
    return PlainTextResponse(text + "\n")


