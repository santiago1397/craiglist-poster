@router.get("/stats")
@_limiter.limit("60/minute")
def stats_endpoint(
    request: Request,
    window: str = Query(default="7d", description="'yesterday', '7d' or '30d'"),
    account: str | None = Query(default=None, description="restrict to one account"),
    limit: int = Query(default=20, ge=1, le=100, description="how many posts to list"),
    format: str = Query(default="text", description="'text' (default) or 'json'"),
    identity: dict = _READ,
):
    """Views and impressions earned during a period — a real difference between
    daily snapshots, not a lifetime average."""
    if window not in ("yesterday", "7d", "30d"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="window must be one of: yesterday, 7d, 30d",
        )
    with conn() as c:
        data = agent_svc.stats_report(c, window=window, account=account, limit=limit)
    return _respond(data, agent_svc.render_stats(data), format)


